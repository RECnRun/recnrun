#!/bin/sh
# Autostart of recnrun-launcher.sh (POC PLAN.md P4.5): a user LaunchAgent on macOS, a systemd user
# unit on Linux. Sourced by recnrun-launcher.sh, which provides log, die, la_script, is_namespace,
# is_directory, system_name, and lc_random.
#
#   autostart on|off|status <state-dir> <record> <namespace>
#
# The plist and the unit are written with printf from five checked values: this script's path, the
# state dir, the record path, the namespace, and HOME. A path is accepted only as letters, digits,
# dot, underscore, hyphen, and slash, so nothing in it can end an XML string or a unit word (a path
# with a space is refused). Nothing the record or a state file holds reaches either file. A file
# that lacks the marker comment was not generated here and is neither overwritten nor removed (65).
# Where systemd --user is missing, "on" exits 70 and prints the command that runs the launcher in
# the background instead.

AGENT_LABEL=com.recnrun.launcher
UNIT_NAME=recnrun-launcher.service
MARKER='generated by recnrun-launcher.sh autostart'
USAGE_AUTOSTART='usage: autostart on|off|status <state-dir> <record> <namespace>'

is_unit_path() {
  is_directory "$1" || return 1
  case $1 in *[!A-Za-z0-9._/-]*) return 1 ;; esac
  return 0
}
check_values() {
  if ! is_unit_path "$au_state" || [ ! -d "$au_state" ]; then die 65 'the state directory is not an existing absolute directory of plain path characters'; fi
  if ! is_unit_path "$au_record" || [ ! -f "$au_record" ]; then die 65 'the record is not an existing absolute file of plain path characters'; fi
  is_namespace "$au_ns" || die 65 'the namespace is not a namespace'
  if ! is_unit_path "$au_script" || [ ! -f "$au_script" ]; then die 65 'this script lives at a path with characters outside letters, digits, dot, underscore, hyphen, and slash'; fi
  if ! is_unit_path "${HOME:-}" || [ ! -d "$HOME" ]; then die 65 'HOME is not an existing absolute directory of plain path characters'; fi
}
# Refuses a file that exists and is not ours.
claim() {
  [ -e "$1" ] || [ -L "$1" ] || return 0
  if [ -L "$1" ] || [ ! -f "$1" ] || ! grep -Fq -- "$MARKER" "$1"; then die 65 "$1 was not generated by this script: left alone"; fi
}
# Writes the output of the function $2 to the file $1 by a rename.
write_generated() {
  mkdir -p -- "$(dirname -- "$1")"
  wg_tmp=$1.$(lc_random).tmp
  (
    set -C
    "$2" >"$wg_tmp"
  ) || die 73 "cannot write $1"
  mv -f -- "$wg_tmp" "$1" || die 73 "cannot replace $1"
}

# --- macOS: LaunchAgent ----------------------------------------------------------------------

emit_plist() {
  printf '%s\n' '<?xml version="1.0" encoding="UTF-8"?>' \
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">' \
    "<!-- $MARKER -->" '<plist version="1.0">' '<dict>' \
    '  <key>Label</key>' "  <string>$AGENT_LABEL</string>" \
    '  <key>ProgramArguments</key>' '  <array>' '    <string>/bin/sh</string>' \
    "    <string>$au_script</string>" '    <string>start</string>' "    <string>$au_state</string>" \
    "    <string>$au_record</string>" "    <string>$au_ns</string>" '  </array>' \
    '  <key>RunAtLoad</key>' '  <true/>' '  <key>KeepAlive</key>' '  <false/>' \
    '  <key>StandardOutPath</key>' "  <string>$au_state/launcher.log</string>" \
    '  <key>StandardErrorPath</key>' "  <string>$au_state/launcher.log</string>" \
    '</dict>' '</plist>'
}
autostart_darwin() {
  ad_plist=$HOME/Library/LaunchAgents/$AGENT_LABEL.plist
  ad_domain=gui/$(id -u)
  command -v launchctl >/dev/null 2>&1 || die 70 'launchctl is not available'
  claim "$ad_plist"
  case $1 in
    on)
      write_generated "$ad_plist" emit_plist
      if command -v plutil >/dev/null 2>&1 && ! plutil -lint "$ad_plist" >&2; then
        rm -f -- "$ad_plist"
        die 70 'plutil rejected the generated plist: removed'
      fi
      launchctl bootout "$ad_domain/$AGENT_LABEL" >/dev/null 2>&1 || :
      launchctl bootstrap "$ad_domain" "$ad_plist" || die 70 "launchctl bootstrap failed; $ad_plist stays"
      log "autostart on: $ad_plist"
      ;;
    off)
      launchctl bootout "$ad_domain/$AGENT_LABEL" >/dev/null 2>&1 || :
      rm -f -- "$ad_plist"
      log 'autostart off'
      ;;
    status)
      if [ -f "$ad_plist" ]; then printf 'plist present %s\n' "$ad_plist"; else printf 'plist absent\n'; fi
      if launchctl print "$ad_domain/$AGENT_LABEL" >/dev/null 2>&1; then printf 'loaded yes\n'; else printf 'loaded no\n'; fi
      ;;
  esac
}

# --- Linux: systemd --user -------------------------------------------------------------------

emit_unit() {
  printf '%s\n' "# $MARKER" '[Unit]' 'Description=RECnRun launcher' '' '[Service]' \
    "ExecStart=/bin/sh $au_script start $au_state $au_record $au_ns" \
    'Restart=on-failure' "StandardOutput=append:$au_state/launcher.log" \
    "StandardError=append:$au_state/launcher.log" '' '[Install]' 'WantedBy=default.target'
}
background_command() {
  printf 'systemd --user is not available. Run the launcher in the background yourself:\n'
  printf '  sh %s start %s %s %s >>%s/launcher.log 2>&1 &\n' "$au_script" "$au_state" "$au_record" "$au_ns" "$au_state"
  printf 'Its log is %s/launcher.log\n' "$au_state"
}
# Without systemctl: "on" prints the background command and exits 70; the others only report.
autostart_without_systemd() {
  case $1 in
    on)
      background_command
      exit 70
      ;;
    off) rm -f -- "$al_unit" ;;
    status) printf 'systemd unavailable\n' ;;
  esac
}
autostart_linux() {
  al_unit=$HOME/.config/systemd/user/$UNIT_NAME
  claim "$al_unit"
  command -v systemctl >/dev/null 2>&1 || { autostart_without_systemd "$1"; return 0; }
  case $1 in
    on)
      write_generated "$al_unit" emit_unit
      if command -v systemd-analyze >/dev/null 2>&1 && ! systemd-analyze --user verify "$al_unit" >&2; then
        rm -f -- "$al_unit"
        die 70 'systemd-analyze rejected the generated unit: removed'
      fi
      systemctl --user enable --now "$UNIT_NAME" || die 70 "systemctl enable failed; $al_unit stays"
      log "autostart on: $al_unit"
      ;;
    off)
      systemctl --user disable --now "$UNIT_NAME" >/dev/null 2>&1 || :
      rm -f -- "$al_unit"
      log 'autostart off'
      ;;
    status)
      if [ -f "$al_unit" ]; then printf 'unit present %s\n' "$al_unit"; else printf 'unit absent\n'; fi
      printf 'enabled %s\n' "$(systemctl --user is-enabled "$UNIT_NAME" 2>/dev/null || :)"
      printf 'active %s\n' "$(systemctl --user is-active "$UNIT_NAME" 2>/dev/null || :)"
      ;;
  esac
}

cmd_autostart() {
  [ "$#" -eq 4 ] || die 64 "$USAGE_AUTOSTART"
  case $1 in on | off | status) ;; *) die 64 "$USAGE_AUTOSTART" ;; esac
  au_state=$2 au_record=$3 au_ns=$4 au_script=${la_script:-}
  check_values
  case $(system_name) in
    Darwin) autostart_darwin "$1" ;;
    Linux) autostart_linux "$1" ;;
    *) die 70 'autostart is not available on this system' ;;
  esac
}
