import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { NAMESPACE, shells } from "./lab.mjs";
import { commandScene, launcher, launcherScript, pathWithout } from "./commands-lab.mjs";

const EX_REFUSED = 65;
const EX_FAILED = 70;
const LABEL = "com.recnrun.launcher";
const MARKER = "generated by recnrun-launcher.sh autostart";
const has = (command) => spawnSync("sh", ["-c", `command -v ${command}`]).status === 0;

/** A scene whose HOME is the fixture and whose PATH starts with the recording stubs. */
function autostartScene(context, uname, extra = {}) {
  const scene = commandScene(context);
  const vars = (more) =>
    scene.vars({
      RECNRUN_DISCOVERY_UNAME: uname,
      PATH: `${scene.stubs}:${process.env.PATH}`,
      ...extra,
      ...more,
    });
  const run = (shell, action, ...rest) =>
    launcher(
      shell,
      ["autostart", action, rest[0] ?? scene.state, rest[1] ?? scene.record, rest[2] ?? NAMESPACE],
      vars(),
    );
  return {
    ...scene,
    vars,
    run,
    plist: join(scene.home, "Library/LaunchAgents", `${LABEL}.plist`),
    unit: join(scene.home, ".config/systemd/user/recnrun-launcher.service"),
  };
}
const uid = process.getuid?.() ?? 0;

for (const shell of shells) {
  await test(`${shell}: autostart on writes a LaunchAgent and loads it; off unloads and removes it`, (context) => {
    const scene = autostartScene(context, "Darwin");
    const on = scene.run(shell, "on");
    assert.equal(on.code, 0, on.err);
    const text = readFileSync(scene.plist, "utf8");
    assert.ok(text.includes(`<!-- ${MARKER} -->`));
    assert.ok(text.includes(`<string>${LABEL}</string>`));
    for (const value of ["/bin/sh", launcherScript, "start", scene.state, scene.record, NAMESPACE])
      assert.ok(text.includes(`<string>${value}</string>`), `${value} in the plist`);
    assert.match(text, /<key>RunAtLoad<\/key>\s*<true\/>/);
    assert.match(text, /<key>KeepAlive<\/key>\s*<false\/>/);
    assert.ok(text.includes(`<string>${scene.state}/launcher.log</string>`));
    assert.ok(scene.calls().includes(`launchctl bootstrap gui/${uid} ${scene.plist}`));
    const loaded = scene.run(shell, "status");
    assert.match(loaded.out, /plist present/);
    assert.match(loaded.out, /loaded yes/);
    const off = scene.run(shell, "off");
    assert.equal(off.code, 0, off.err);
    assert.ok(scene.calls().includes(`launchctl bootout gui/${uid}/${LABEL}`));
    assert.equal(existsSync(scene.plist), false);
    assert.match(scene.run(shell, "status").out, /plist absent/);
  });

  await test(
    `${shell}: the generated plist passes plutil -lint`,
    { skip: !has("plutil") && "plutil is not installed" },
    (context) => {
      const scene = autostartScene(context, "Darwin");
      assert.equal(scene.run(shell, "on").code, 0);
      const lint = spawnSync("plutil", ["-lint", scene.plist], { encoding: "utf8" });
      assert.equal(lint.status, 0, lint.stdout + lint.stderr);
    },
  );

  await test(`${shell}: a plist this script did not generate is never overwritten or removed`, (context) => {
    const scene = autostartScene(context, "Darwin");
    mkdirSync(join(scene.home, "Library/LaunchAgents"), { recursive: true });
    writeFileSync(scene.plist, "<plist>someone else</plist>\n");
    for (const action of ["on", "off"])
      assert.equal(scene.run(shell, action).code, EX_REFUSED, action);
    assert.equal(readFileSync(scene.plist, "utf8"), "<plist>someone else</plist>\n");
    assert.equal(scene.calls().length, 0, "launchctl was not called");
  });

  await test(`${shell}: autostart on writes a systemd user unit and enables it; off disables it`, (context) => {
    const scene = autostartScene(context, "Linux");
    const on = scene.run(shell, "on");
    assert.equal(on.code, 0, on.err);
    const text = readFileSync(scene.unit, "utf8");
    assert.ok(text.includes(`# ${MARKER}`));
    assert.ok(
      text.includes(
        `ExecStart=/bin/sh ${launcherScript} start ${scene.state} ${scene.record} ${NAMESPACE}\n`,
      ),
    );
    assert.match(text, /^Restart=on-failure$/m);
    assert.match(text, /^WantedBy=default\.target$/m);
    const calls = scene.calls();
    assert.ok(calls.includes(`systemd-analyze --user verify ${scene.unit}`), calls.join("\n"));
    assert.ok(calls.includes("systemctl --user enable --now recnrun-launcher.service"));
    assert.equal(scene.run(shell, "off").code, 0);
    assert.ok(scene.calls().includes("systemctl --user disable --now recnrun-launcher.service"));
    assert.equal(existsSync(scene.unit), false);
  });

  await test(`${shell}: a unit this script did not generate is refused`, (context) => {
    const scene = autostartScene(context, "Linux");
    mkdirSync(join(scene.home, ".config/systemd/user"), { recursive: true });
    writeFileSync(scene.unit, "[Unit]\nDescription=mine\n");
    assert.equal(scene.run(shell, "on").code, EX_REFUSED);
    assert.equal(readFileSync(scene.unit, "utf8"), "[Unit]\nDescription=mine\n");
  });

  await test(`${shell}: a failing verifier removes the unit and loads nothing`, (context) => {
    const scene = autostartScene(context, "Linux", { STUB_ANALYZE_RC: "1" });
    assert.equal(scene.run(shell, "on").code, EX_FAILED);
    assert.equal(existsSync(scene.unit), false);
    assert.ok(!scene.calls().some((call) => call.includes("enable")));
  });

  await test(`${shell}: without systemctl, autostart on exits 70 and prints the background command`, (context) => {
    const scene = autostartScene(context, "Linux");
    const bare = pathWithout(scene.home, ["systemctl", "systemd-analyze"]);
    const result = launcher(
      shell,
      ["autostart", "on", scene.state, scene.record, NAMESPACE],
      scene.vars({ RECNRUN_DISCOVERY_UNAME: "Linux", PATH: bare }),
    );
    assert.equal(result.code, EX_FAILED, result.err);
    assert.ok(
      result.out.includes(
        `sh ${launcherScript} start ${scene.state} ${scene.record} ${NAMESPACE} >>${scene.state}/launcher.log 2>&1 &`,
      ),
      result.out,
    );
    assert.equal(existsSync(scene.unit), false);
  });

  await test(`${shell}: a value with a space or a quote never reaches the plist or the unit`, (context) => {
    const scene = autostartScene(context, "Darwin");
    const bad = [
      `${scene.home}/a record`,
      `${scene.home}/it's`,
      `${scene.home}/q"uote`,
      `${scene.home}/a<b`,
    ];
    for (const name of bad) {
      writeFileSync(name, "");
      mkdirSync(`${name}.d`);
      for (const [uname, file] of [
        ["Darwin", scene.plist],
        ["Linux", scene.unit],
      ]) {
        const vars = scene.vars({ RECNRUN_DISCOVERY_UNAME: uname });
        const asRecord = launcher(shell, ["autostart", "on", scene.state, name, NAMESPACE], vars);
        const asState = launcher(
          shell,
          ["autostart", "on", `${name}.d`, scene.record, NAMESPACE],
          vars,
        );
        assert.equal(asRecord.code, EX_REFUSED, name);
        assert.equal(asState.code, EX_REFUSED, name);
        assert.equal(existsSync(file), false);
      }
    }
    assert.equal(scene.calls().length, 0);
    assert.equal(scene.run(shell, "on", scene.state, scene.record, "Lab 1").code, EX_REFUSED);
  });

  await test(`${shell}: nothing a record block holds reaches the plist`, (context) => {
    const scene = autostartScene(context, "Darwin");
    writeFileSync(
      scene.record,
      `${readFileSync(scene.record, "utf8")}\nuserDataDir=/x"><string>evil</string>\nprofileId=evil\nnamespace=${NAMESPACE}\n`,
    );
    assert.equal(scene.run(shell, "on").code, 0);
    assert.ok(!readFileSync(scene.plist, "utf8").includes("evil"));
  });

  await test(`${shell}: a wrong call exits 64 and an unknown system 70`, (context) => {
    const scene = autostartScene(context, "Plan9");
    const call = (...args) => launcher(shell, ["autostart", ...args], scene.vars());
    assert.equal(call().code, 64);
    assert.equal(call("on").code, 64);
    assert.equal(call("restart", scene.state, scene.record, NAMESPACE).code, 64);
    assert.equal(call("on", scene.state, scene.record, NAMESPACE, "extra").code, 64);
    assert.equal(call("on", scene.state, scene.record, NAMESPACE).code, EX_FAILED);
  });
}

await test(
  "systemd-analyze accepts the generated unit",
  { skip: !has("systemd-analyze") && "systemd-analyze is not installed" },
  (context) => {
    const scene = autostartScene(context, "Linux");
    const bare = pathWithout(scene.home, ["systemctl"]);
    const result = launcher(
      "sh",
      ["autostart", "on", scene.state, scene.record, NAMESPACE],
      scene.vars({ PATH: `${scene.stubs}:${bare}` }),
    );
    assert.equal(result.code, 0, result.err);
    const verify = spawnSync("systemd-analyze", ["--user", "verify", scene.unit], {
      encoding: "utf8",
      // A user manager is absent in the container; systemd-analyze only needs the runtime directory to exist.
      env: { ...process.env, XDG_RUNTIME_DIR: scene.home },
    });
    assert.equal(verify.status, 0, verify.stdout + verify.stderr);
  },
);
