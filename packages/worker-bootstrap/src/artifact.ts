import { createHash } from "node:crypto";

/** The variable the IIFE bundle assigns; it stays local to BOOTSTRAP_SOURCE's function. */
export const BUNDLE_NAME = "recnrunBootstrap";

export interface BootstrapArtifact {
  source: string;
  hash: string;
  version: string;
}

/** Type declarations of the generated module that `src/index.ts` imports. */
export const MODULE_TYPES = [
  "export declare const source: string;",
  "export declare const hash: string;",
  "export declare const version: string;",
  "",
].join("\n");

/**
 * Wraps the IIFE bundle in one function expression, valid as a classic script, that installs the
 * marker (`{ marker }`) or the original session's filter (`{ original: true }`) on the global it runs in.
 */
export function renderArtifact(bundle: string, version: string): BootstrapArtifact {
  const source = `(function (options) {\n${bundle.trim()}\nreturn ${BUNDLE_NAME}.installBootstrap(globalThis, options);\n})`;
  return { source, hash: createHash("sha256").update(source).digest("hex"), version };
}

/** The ES module that carries the artifact to `src/index.ts`. */
export function renderModule(artifact: BootstrapArtifact): string {
  return [
    "// Generated by packages/worker-bootstrap/vite.config.ts; do not edit.",
    `export const source = ${JSON.stringify(artifact.source)};`,
    `export const hash = ${JSON.stringify(artifact.hash)};`,
    `export const version = ${JSON.stringify(artifact.version)};`,
    "",
  ].join("\n");
}
